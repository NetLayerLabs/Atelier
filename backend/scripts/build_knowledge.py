"""Build the knowledge-library documents Atelier generates from the Brand workspace.

    cd backend && uv run python scripts/build_knowledge.py

Writes, into $ATELIER_DATA_DIR/knowledge/ (default backend/var/knowledge/, git-ignored):
* supplier-catalogue.md/.pdf - the brand's supplier directory (services/knowledge.supplier_catalogue_markdown:
  categories, capabilities, certifications with expiry, MOQ, lead time, payment terms; no contact addresses);
* brand-profile.md/.pdf - the brand profile (voice, price architecture, colour standards, sizes, promise).

The brand's own brand-book files are not generated: they are uploaded in the Brand workspace (and sent to the
Evolus library from there). scripts/provision_evolus.py uploads these PDFs plus the brand-book files.
Nothing here is invented: an empty workspace produces no documents.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from reportlab.lib import colors  # noqa: E402
from reportlab.lib.pagesizes import A4  # noqa: E402
from reportlab.lib.styles import ParagraphStyle  # noqa: E402
from reportlab.lib.units import mm  # noqa: E402
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle  # noqa: E402

from app.services import knowledge, workspace  # noqa: E402

FOOTER = "Generated by Atelier from the brand's workspace."


def output_dir() -> Path:
    d = workspace.data_dir() / "knowledge"
    d.mkdir(parents=True, exist_ok=True)
    return d


# --------------------------------------------------------------------------- Markdown -> PDF (enough for our docs)


def _inline(text: str) -> str:
    text = text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    text = re.sub(r"\*\*(.+?)\*\*", r"<b>\1</b>", text)
    text = re.sub(r"(?<![\w*])_(.+?)_(?!\w)", r"<i>\1</i>", text)
    text = re.sub(r"`(.+?)`", r"<font face='Courier'>\1</font>", text)
    return text


def markdown_pdf(md: str, out: Path, title: str) -> None:
    body = re.sub(r"^---.*?---\s*", "", md, flags=re.DOTALL)
    st = {
        "h1": ParagraphStyle("h1", fontName="Times-Bold", fontSize=20, leading=24, spaceAfter=8),
        "h2": ParagraphStyle("h2", fontName="Times-Bold", fontSize=14, leading=18, spaceBefore=10, spaceAfter=4),
        "h3": ParagraphStyle("h3", fontName="Helvetica-Bold", fontSize=10.5, leading=14, spaceBefore=6, spaceAfter=2),
        "p": ParagraphStyle("p", fontName="Helvetica", fontSize=9, leading=12.5, spaceAfter=4),
        "q": ParagraphStyle("q", fontName="Helvetica-Oblique", fontSize=8.5, leading=11.5, leftIndent=8,
                            textColor=colors.HexColor("#6B655C"), spaceAfter=4),
        "li": ParagraphStyle("li", fontName="Helvetica", fontSize=9, leading=12.5, leftIndent=10, bulletIndent=2),
        "td": ParagraphStyle("td", fontName="Helvetica", fontSize=7.4, leading=9.2),
    }
    flow: list = []
    lines = body.splitlines()
    i = 0
    while i < len(lines):
        line = lines[i].rstrip()
        if line.startswith("|"):
            rows = []
            while i < len(lines) and lines[i].startswith("|"):
                cells = [c.strip() for c in lines[i].strip().strip("|").split("|")]
                if not all(re.fullmatch(r":?-{2,}:?", c) for c in cells):
                    rows.append([Paragraph(_inline(c), st["td"]) for c in cells])
                i += 1
            t = Table(rows, repeatRows=1, hAlign="LEFT")
            t.setStyle(TableStyle([("GRID", (0, 0), (-1, -1), 0.3, colors.HexColor("#D9D3C7")),
                                   ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#F3EEE6")),
                                   ("VALIGN", (0, 0), (-1, -1), "TOP")]))
            flow += [t, Spacer(1, 6)]
            continue
        if line.startswith("### "):
            flow.append(Paragraph(_inline(line[4:]), st["h3"]))
        elif line.startswith("## "):
            flow.append(Paragraph(_inline(line[3:]), st["h2"]))
        elif line.startswith("# "):
            flow.append(Paragraph(_inline(line[2:]), st["h1"]))
        elif line.startswith(">"):
            flow.append(Paragraph(_inline(line.lstrip("> ")), st["q"]))
        elif re.match(r"^(\s*[-*]|\s*\d+\.)\s", line):
            text = re.sub(r"^\s*([-*]|\d+\.)\s+", "", line)
            while i + 1 < len(lines) and lines[i + 1].startswith("  ") and not re.match(r"^\s*([-*]|\d+\.)\s", lines[i + 1]):
                i += 1
                text += " " + lines[i].strip()
            flow.append(Paragraph(_inline(text), st["li"], bulletText="•"))
        elif line.strip():
            flow.append(Paragraph(_inline(line), st["p"]))
        i += 1

    def footer(c, _doc):
        c.saveState()
        c.setFont("Helvetica", 7)
        c.setFillColor(colors.HexColor("#9A9389"))
        c.drawString(16 * mm, 9 * mm, f"{title} · {FOOTER}")
        c.drawRightString(A4[0] - 16 * mm, 9 * mm, str(c.getPageNumber()))
        c.restoreState()

    doc = SimpleDocTemplate(str(out), pagesize=A4, leftMargin=16 * mm, rightMargin=16 * mm, topMargin=16 * mm,
                            bottomMargin=16 * mm, title=title, author=workspace.brand_name() or "Atelier")
    doc.build(flow, onFirstPage=footer, onLaterPages=footer)


def build() -> list[Path]:
    """Write the generated documents; returns the PDFs (empty when the workspace has nothing to describe)."""
    out: list[Path] = []
    docs = []
    if workspace.suppliers():
        docs.append(("supplier-catalogue", knowledge.supplier_catalogue_markdown()))
    prof = knowledge.profile_markdown()
    if prof:
        docs.append(("brand-profile", prof))
    d = output_dir()
    for stem, md in docs:
        (d / f"{stem}.md").write_text(md, encoding="utf-8")
        pdf = d / f"{stem}.pdf"
        m = re.search(r"^#\s+(.+)$", md, re.MULTILINE)
        markdown_pdf(md, pdf, m.group(1).strip() if m else stem)
        out.append(pdf)
    return out


def main() -> int:
    pdfs = build()
    if not pdfs:
        print("The brand workspace is empty - add the brand profile and suppliers first (Brand workspace).")
        return 1
    for p in pdfs:
        print(f"wrote {p} ({p.stat().st_size // 1024} KB)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
