"""Knowledge grounding - v5: the brand's own documents from the Brand workspace.

Sources (all from services/workspace.py, nothing bundled):
  * brand book documents the brand uploaded (PDF / DOCX / Markdown; text extracted locally on upload);
  * the supplier catalogue, generated from the brand's supplier directory (`supplier_catalogue_markdown`);
  * the brand profile (price architecture, colour standards, size range, promise).

Live: uploaded brand-book files are also sent to the Evolus knowledge library (EVOLUS_LIBRARY_ID) attached to the
Evolus agent, so agent replies are grounded in them; with EVOLUS_AGENT_TRANSPORT=rest the platform's own citations
come back too (library="evolus").

Prompt grounding for every live path: a small keyword search over the same texts here, labelled library="local".
Either way the agent's outputs carry `Citation`s that name the real source document.
"""

from __future__ import annotations

import logging
import math
import re
from pathlib import Path

from ..config import get_settings
from ..models import Citation
from ..workspace_models import EvolusUpload
from . import workspace

log = logging.getLogger("atelier.knowledge")

CATALOGUE_ID = "supplier-catalogue"
PROFILE_ID = "brand-profile"
_WORD = re.compile(r"[a-z0-9]+")
_STOP = set("the a an and or of to in for on with by is are be at as from this that it its we our your per "
            "not no all any each must should can may will one two".split())
_cache: dict[tuple[str, int], list[dict]] = {}


def _tokens(text: str) -> list[str]:
    return [w for w in _WORD.findall(text.lower()) if w not in _STOP and len(w) > 1]


def _title(md: str, fallback: str) -> str:
    m = re.search(r"^title:\s*(.+)$", md, re.MULTILINE) or re.search(r"^#\s+(.+)$", md, re.MULTILINE)
    return m.group(1).strip() if m else fallback


# --------------------------------------------------------------------------- workspace -> markdown


def supplier_catalogue_markdown() -> str:
    """The brand's supplier directory as a knowledge document (no contact addresses: the agent never needs them,
    and this text is uploaded to the Evolus library)."""
    sups = workspace.suppliers()
    brand = workspace.brand_name() or "Brand"
    out = [f"# {brand} - Supplier Catalogue", "",
           "Generated by Atelier from the brand's supplier directory (Brand workspace). Terms are each supplier's "
           "standard offer as recorded by the brand; a quote document from the supplier always takes precedence.", ""]
    for s in sups:
        region = ", ".join(x for x in (s.city, s.country) if x) or "location not recorded"
        certs = ", ".join(c.name + (f" (expires {c.expires_on}{', EXPIRED' if c.expired else ''})" if c.expires_on
                                    else "") for c in s.certifications) or "none recorded"
        out += [f"## {s.name} - {region}", ""]
        out.append(f"- **Type:** {'Cut-make-trim / full-package maker' if s.maker else 'Supplier'}"
                   + (f"; categories: {', '.join(s.categories)}" if s.categories else "") + ".")
        if s.capabilities:
            out.append(f"- **Capabilities:** {'; '.join(s.capabilities)}.")
        out.append(f"- **Certifications:** {certs}.")
        if s.moq:
            out.append(f"- **Typical MOQ:** {s.moq:,} pieces.")
        if s.lead_time_weeks:
            out.append(f"- **Typical lead time:** {s.lead_time_weeks} weeks.")
        if s.payment_terms:
            out.append(f"- **Payment terms:** {s.payment_terms}.")
        out.append(f"- **Correspondence language:** {s.language}.")
        if s.notes:
            out.append(f"- **Brand notes:** {s.notes}")
        out.append("")
    return "\n".join(out)


def profile_markdown() -> str:
    p = workspace.profile()
    if p is None:
        return ""
    out = [f"# {p.name} - Brand profile", "", "Entered by the brand in Atelier's Brand workspace.", ""]
    if p.voice:
        out += ["## Voice and persona", "", p.voice, ""]
    facts = [f"- Currency: {p.currency}"]
    if p.target_markets:
        facts.append(f"- Target markets: {', '.join(p.target_markets)}")
    if p.default_size_range:
        facts.append(f"- Default size range: {', '.join(p.default_size_range)}")
    if p.delivery_promise_weeks:
        facts.append(f"- Delivery promise: {p.delivery_promise_weeks} weeks from launch")
    if p.preorder_window_days:
        facts.append(f"- Pre-order window: {p.preorder_window_days} days")
    if p.price_architecture:
        pa = p.price_architecture
        facts.append(f"- Price architecture: {'retail = ' + format(pa.value, 'g') + 'x landed cost' if pa.mode == 'retail_multiple' else 'target gross margin ' + format(pa.value, 'g') + '%'}")
    out += ["## Commercial rules", "", *facts, ""]
    if p.colours:
        out += ["## Colour standards", ""]
        out += [f"- {c.name}: {c.hex}" + (f" ({c.code})" if c.code else "") for c in p.colours]
        out.append("")
    pts = workspace.size_points()
    if pts:
        out += ["## Size blocks and points of measure", ""]
        for block in sorted({x.block for x in pts}):
            rows = [x for x in pts if x.block == block]
            out.append(f"### {block}")
            out += [f"- {x.point_of_measure}, size {x.size}: {x.value:g} {x.unit}"
                    + (f" (± {x.tolerance:g})" if x.tolerance is not None else "") for x in rows[:200]]
            out.append("")
    return "\n".join(out)


def _sources() -> list[tuple[str, str, str]]:
    """(title, document id, text) for every grounding source in the workspace."""
    out: list[tuple[str, str, str]] = []
    for d in workspace.documents("brand_book"):
        text = workspace.document_text(d.id)
        if text.strip():
            out.append((_title(text, Path(d.filename).stem), d.id, text))
    prof = profile_markdown()
    if prof:
        out.append((_title(prof, "Brand profile"), PROFILE_ID, prof))
    if workspace.suppliers():
        cat = supplier_catalogue_markdown()
        out.append((_title(cat, "Supplier Catalogue"), CATALOGUE_ID, cat))
    return out


def _split(title: str, doc_id: str, text: str) -> list[dict]:
    body = re.sub(r"^---.*?---\s*", "", text, flags=re.DOTALL)
    out: list[dict] = []
    heading = title
    buf: list[str] = []

    def flush() -> None:
        content = "\n".join(buf).strip()
        # Long sections (PDF pages, unheaded DOCX) are cut into ~900-character passages.
        while content:
            piece = content
            if len(content) > 1200:
                cut = content.rfind("\n", 0, 900)
                cut = cut if cut > 300 else content.rfind(" ", 0, 900)
                piece = content[: max(cut, 300)]
            out.append({"doc": title, "file": doc_id, "heading": heading, "text": piece.strip(),
                        "tokens": _tokens(heading + " " + piece)})
            content = content[len(piece):].strip()

    for line in body.splitlines():
        if re.match(r"^#{2,3}\s", line):
            flush()
            buf = []
            heading = line.lstrip("#").strip()
        else:
            buf.append(line)
    flush()
    return out


def chunks() -> list[dict]:
    """Heading-level passages of every workspace source (cached per workspace revision)."""
    key = workspace.revision()
    hit = _cache.get(key)
    if hit is not None:
        return hit
    out: list[dict] = []
    for title, doc_id, text in _sources():
        out += _split(title, doc_id, text)
    _cache.clear()
    _cache[key] = out
    return out


def passage_count(doc_id: str) -> int:
    text = workspace.document_text(doc_id)
    return len(_split("x", doc_id, text)) if text else 0


def local_search(query: str, k: int = 4) -> list[Citation]:
    docs = chunks()
    if not docs:
        return []
    q = _tokens(query)
    if not q:
        return []
    n = len(docs)
    df: dict[str, int] = {}
    for d in docs:
        for t in set(d["tokens"]):
            df[t] = df.get(t, 0) + 1
    scored = []
    for d in docs:
        tf: dict[str, int] = {}
        for t in d["tokens"]:
            tf[t] = tf.get(t, 0) + 1
        score = sum((1 + math.log(tf[t])) * math.log(1 + n / df[t]) for t in set(q) if t in tf)
        if score > 0:
            scored.append((score / math.sqrt(len(d["tokens"]) + 10), d))
    scored.sort(key=lambda x: -x[0])
    return [Citation(source=f"{d['doc']} - {d['heading']}" if d["heading"] != d["doc"] else d["doc"],
                     snippet=_snip(d["text"]), library="local", document_id=d["file"], score=round(s, 3))
            for s, d in scored[:k]]


def _snip(text: str, limit: int = 420) -> str:
    t = re.sub(r"\s+", " ", text).strip()
    return t if len(t) <= limit else t[: limit - 1].rsplit(" ", 1)[0] + "…"


async def search(query: str, k: int | None = None) -> tuple[list[Citation], str]:
    """Passages for the prompt. Evolus has no standalone library-search endpoint (the agent answers from the
    attached library; REST /ask returns its citations), so prompt passages come from the same documents in
    the workspace and are labelled library="local". Returns (citations, where)."""
    return local_search(query, k or get_settings().evolus_library_top_k), "local"


def context_block(citations: list[Citation]) -> str:
    """Retrieved passages formatted for a prompt, numbered so the model can cite them."""
    if not citations:
        return ""
    lines = ["Knowledge library passages (cite by [number] and follow them):"]
    for i, c in enumerate(citations, 1):
        lines.append(f"[{i}] {c.source}: {c.snippet or ''}")
    return "\n".join(lines)


# --------------------------------------------------------------------------- Evolus knowledge library upload


async def upload_to_library(filename: str, data: bytes, content_type: str) -> EvolusUpload:
    """Send a brand-book file to the Evolus knowledge library (same call as scripts/provision_evolus.py).
    Not configured -> status "not_configured" (the local text is still used for grounding)."""
    from . import evolus
    from .http import async_client

    s = get_settings()
    if not s.evolus_library_live:
        return EvolusUpload(status="not_configured",
                            detail="Evolus library not configured (EVOLUS_LIBRARY_ID); "
                                   "used for local grounding only")
    lib = s.evolus_library_id.strip()
    try:
        async with async_client(60.0) as c:
            r = await c.post(evolus._url(f"/api/v1/memories/{lib}/documents?language=en"),
                             headers=evolus.library_headers(), files={"file": (filename, data, content_type)})
        if r.status_code >= 400:
            return EvolusUpload(status="failed", library_id=lib, detail=evolus._explain(r)[:300])
        try:
            body = r.json()
        except ValueError:
            body = {}
        doc_id = evolus.find_key(body, "id", "documentId")
        evolus._doc_titles.clear()  # citation titles are re-listed on the next agent call
        return EvolusUpload(status="uploaded", library_id=lib, document_id=str(doc_id) if doc_id else None)
    except Exception as e:  # noqa: BLE001
        log.warning("Evolus library upload failed: %s", e)
        return EvolusUpload(status="failed", library_id=lib, detail=str(e)[:300])
