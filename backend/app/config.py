"""Runtime configuration.

Every env var from CONTRACT.md is declared here. There is no mock mode (CONTRACT.md "v5"): a service is
*configured* when its env vars are present, and every request goes to the real service. A service that is not
configured, or fails, surfaces as an honest error with a setup hint; nothing is ever made up in its place.
The `*_live` properties below mean "configured" (the name is kept from earlier versions).
"""

from __future__ import annotations

from functools import lru_cache
from pathlib import Path
from urllib.parse import urlparse

from pydantic_settings import BaseSettings, SettingsConfigDict

BACKEND_DIR = Path(__file__).resolve().parent.parent
STATIC_DIR = BACKEND_DIR / "static"
GENERATED_DIR = STATIC_DIR / "generated"
UPLOADS_DIR = STATIC_DIR / "uploads"


class Settings(BaseSettings):
    model_config = SettingsConfigDict(
        env_file=BACKEND_DIR / ".env", env_file_encoding="utf-8", extra="ignore"
    )

    # --- contract env vars -------------------------------------------------
    # Default plan (CONTRACT.md "v6"): ONE vLLM server on the MI300X serving google/gemma-4-26B-A4B-it is both the
    # text brain and the vision model, so AMD_VLLM_* and AMD_VISION_* point at the same endpoint.
    amd_vllm_endpoint: str = ""  # OpenAI-compatible base URL, e.g. http://host:8000/v1
    amd_vllm_model: str = ""  # empty -> first model reported by GET /v1/models
    amd_vllm_api_key: str = ""  # also used for the vision endpoint

    amd_vision_endpoint: str = ""  # OpenAI-compatible base URL serving a VLM (default: the same Gemma 4 server)
    amd_vision_model: str = ""

    amd_diffusion_endpoint: str = ""  # full URL; see services/diffusion.py::_call_diffusion_endpoint

    # Evolus REST API - https://evolus.ai/developers (verified 2026-10-12 against the public docs).
    evolus_api_base: str = "https://api.evolus.ai"
    evolus_api_key: str = ""  # application API key (workspace "API keys" page) -> X-ApiKey
    evolus_workspace_id: str = ""  # the workspace/space id -> X-Application-Id
    evolus_outreach_workflow_id: str = ""
    evolus_shopify_workflow_id: str = ""
    # v2 knobs: paths are templates so they can be corrected on site without code changes.
    evolus_execute_path: str = "/api/v1/workflows/{workflow_id}/execute"
    evolus_status_path: str = "/api/v1/workflows/{workflow_id}/executions/{execution_id}"
    evolus_probe_path: str = "/api/v1/ai-tools"  # cheap authenticated GET used by /api/health
    evolus_api_key_header: str = "X-ApiKey"
    evolus_app_id_header: str = "X-Application-Id"
    evolus_send_parameters: bool = True  # send the flat `parameters` form field (retried without on 400/422)
    evolus_poll_interval: float = 1.5  # seconds between GET .../executions/{id}
    evolus_poll_timeout: float = 60.0  # stop waiting (the run keeps going in Evolus; RFQs stay "queued")
    evolus_probe_cache_seconds: float = 30.0  # Evolus allows 60 req/min per event workspace
    evolus_agent_model: str = ""  # v3: "<applicationId>:<agentId>" - the Evolus agent that is the brain (see v3 below)

    # --- v3: Evolus as the agent's brain + real supplier quotes (CONTRACT.md "v3") ------------
    # Agent chat over Evolus's OpenAI-compatible endpoint. EVOLUS_AGENT_MODEL = "<applicationId>:<agentId>";
    # the agent's own model is our AMD vLLM endpoint (connected in the workspace). When set (and live),
    # tech packs, RFQs, creative direction and the supplier rationale are generated by that agent.
    evolus_chat_base: str = ""  # default: EVOLUS_API_BASE; the OpenAI-compatible root (we append /v1/...)
    evolus_chat_path: str = "/v1/chat/completions"
    # "openai": POST /v1/chat/completions (model "<appId>:<agentId>", Bearer key) - documented on
    # evolus.ai/developers. "rest": POST /api/v1/agents/{agentId}/ask - also returns the library citations[].
    evolus_agent_transport: str = "openai"
    evolus_ask_path: str = "/api/v1/agents/{agent_id}/ask"
    evolus_agent_timeout: float = 60.0  # QA M12: stage-friendly; a timeout is not retried (falls to direct vLLM)
    evolus_agent_label: str = ""  # optional: the AMD model the agent runs on, for logs (e.g. "gemma-4-26B-A4B-it")
    # Where the agent's own model is served, shown in routes and logs. Must be true: "AMD vLLM" for our own vLLM on
    # an AMD Developer Cloud droplet, "AMD Token Factory" for AMD's hosted, OpenAI-compatible service.
    evolus_agent_backend: str = "AMD vLLM"
    atelier_vision_max_edge: int = 1280  # long edge (px) of images sent to the vision model; keeps requests small
    # Knowledge library ("memory") holding the brand book + supplier catalogue, attached to the agent.
    # Evolus has no standalone search endpoint: the agent answers from it (REST /ask returns citations).
    # The id is used to list document titles (for citations) and by the provisioning / check scripts.
    evolus_library_id: str = ""
    # Optional personal key (Profile → API keys, header X-User-ApiKey). Library ("memories") calls may need it
    # (inferred from a third-party integration); scripts/provision_evolus.py uses it for those calls when set.
    evolus_user_api_key: str = ""
    # The name of our AMD vLLM model as connected in the workspace (Models page) -> agent modelKey "own/<name>".
    evolus_own_model_name: str = ""
    evolus_library_top_k: int = 4  # passages retrieved from the Brand workspace documents to put in the prompt
    # Document extractor for supplier quote PDFs: it hangs off an (extractor) agent.
    evolus_extractor_agent_id: str = ""
    evolus_extractor_id: str = ""
    evolus_extract_path: str = "/api/v1/agents/{agent_id}/json/{extractor_id}/ask-file?useWebhook=false"
    # Optional 5th building block: polish each RFQ body with the Evolus "email" AI Tool (uses credits).
    evolus_rfq_ai_tool: bool = False
    # Email-triggered workflow (inbound quote -> extractor -> our webhook). Only used by check_evolus.py.
    evolus_inbound_workflow_id: str = ""
    # Shared secret the inbound workflow sends to POST /api/webhooks/evolus/quote.
    evolus_webhook_secret: str = ""
    evolus_webhook_header: str = "X-Atelier-Webhook-Secret"
    # v5: supplier contacts (and a per-supplier RFQ override address) live in the Brand workspace, not here.
    # 0 = the quotes step waits until every RFQ'd mill has replied or the CD closes the round.
    atelier_quote_wait_seconds: float = 0.0
    atelier_quote_max_bytes: int = 15_000_000
    # v5: quotes in another currency are converted with the ECB's daily euro reference rates (free, no key).
    # Cached for a day; if the rates can't be loaded the quote stays in its own currency and says so.
    atelier_fx_url: str = "https://www.ecb.europa.eu/stats/eurofxref/eurofxref-daily.xml"
    atelier_fx_timeout: float = 8.0
    atelier_fx_cache_hours: float = 24.0

    # --- v4: brand guardrails + human hand-off (CONTRACT.md "v4") -----------------------------
    # v5: the guardrails are set by the brand in the Brand workspace (no env defaults, nothing invented).
    # Counter-offers are emailed through this Evolus workflow; empty = the outreach workflow (same flat params).
    evolus_negotiation_workflow_id: str = ""
    # Translate supplier notes that are not in English (brain chain; left untranslated, and labelled, without one).
    atelier_translate_notes: bool = True
    # v5: purchase orders are sent to the selected mill through this Evolus workflow (flat params, see
    # docs/EVOLUS_SETUP.md); empty = the outreach workflow. Without Evolus the PO stays a draft, never "issued".
    evolus_po_workflow_id: str = ""

    # --- v5: Brand workspace (CONTRACT.md "v5") ------------------------------
    # Where the brand's data lives: the workspace (SQLite atelier.sqlite3 + uploaded files) and the persisted
    # sequences (sequences.json: PO and style numbers). Default backend/var/ (git-ignored); in Docker the
    # mounted /data volume (docker-compose.yml). Relative paths are under backend/.
    atelier_data_dir: str = ""
    atelier_brand_id: str = "default"  # which brand's sequences to use (one brand per workspace / data dir)

    public_base_url: str = "http://localhost:8787"
    cors_origins: str = "http://localhost:3100,http://127.0.0.1:3100,http://localhost:3000,http://127.0.0.1:3000"
    # QA H5 (app/security.py): state-changing /api requests must come from CORS_ORIGINS (Origin / Referer check).
    # With ATELIER_ADMIN_TOKEN set they also need `Authorization: Bearer <token>` or the dashboard's sign-in cookie;
    # without it only this machine (loopback, or ATELIER_TRUSTED_NETWORKS, comma-separated CIDRs) may change data.
    atelier_admin_token: str = ""
    atelier_trusted_networks: str = ""

    # --- backend-only knobs (not part of the contract) ---------------------
    # QA M12: stage-friendly timeouts; a timeout / connection error is not retried (only a bad answer is).
    atelier_llm_timeout: float = 45.0
    atelier_diffusion_timeout: float = 120.0
    atelier_evolus_timeout: float = 45.0
    atelier_diffusion_width: int = 768
    atelier_diffusion_height: int = 1024

    # --- v2: live infrastructure & inference stats (see CONTRACT.md v2) -----
    # Human label for the accelerator behind the AMD endpoints, shown in the Inference panel.
    # Set it to what the instance really is (e.g. "AMD Instinct MI300X"); never guessed.
    amd_gpu_label: str = ""
    # Optional bearer key for deploy/diffusion_server.py (its DIFFUSION_API_KEY); not needed over an SSH tunnel.
    amd_diffusion_api_key: str = ""
    atelier_vision_timeout: float = 45.0
    # Tail-latency hedging (services/hedge.py): with no answer after this many seconds, send the same request again
    # and use whichever answers first. Hosted queues (AMD Token Factory) have long, random waits. 0 turns it off.
    # Vision answers are short; brain answers (tech packs, RFQs in two languages) legitimately take longer.
    atelier_hedge_vision_after: float = 20.0
    atelier_hedge_brain_after: float = 45.0
    # Hosted demo (only when ATELIER_ADMIN_TOKEN is set): visitors without the token may run the steps with no
    # outside effect (security.PUBLIC_POSTS), within these limits per 10 minutes. 0 = no limit.
    atelier_public_demo: bool = True
    atelier_public_rate_per_visitor: int = 15
    atelier_public_rate_total: int = 120
    atelier_public_uploads_max_mb: int = 1024  # visitors' uploads pause once static/uploads holds this much
    # Images per vision prompt; keep it <= the server's --limit-mm-per-prompt image budget (deploy/: 4).
    atelier_vision_max_images: int = 4
    atelier_extractor_timeout: float = 60.0  # the Evolus document extractor (one synchronous ask-file call)
    # Health probes: per-probe timeout and how long a probe result is cached.
    atelier_health_timeout: float = 2.5
    atelier_health_cache_seconds: float = 5.0
    # Stream LLM/VLM completions to measure time-to-first-token (vLLM reports usage on the last chunk).
    atelier_llm_stream: bool = True
    # Ask vLLM for JSON mode (response_format=json_object) on the first attempt; the retry drops it.
    atelier_llm_json_mode: bool = True
    # Extra JSON merged into every chat request body. backend/.env.example sets
    # '{"chat_template_kwargs": {"enable_thinking": false}}': Gemma 4 (and Qwen3) thinking off for strict-JSON calls.
    atelier_llm_extra_body: str = ""
    # How many inference calls the telemetry ring buffer keeps.
    atelier_telemetry_size: int = 300

    # --- v3: real Shopify pre-orders (see CONTRACT.md v3, docs/SHOPIFY_SETUP.md) -----
    # The dev store, e.g. "atelier-demo.myshopify.com". A full origin ("http://127.0.0.1:18903") is accepted too,
    # which is how tests/fake_upstreams.py's fake Shopify is wired in for rehearsals.
    shopify_store_domain: str = ""
    # Admin API access token (X-Shopify-Access-Token). Either set it directly (shpat_…, legacy custom app) or set
    # the Dev Dashboard app's client id + secret and the backend fetches (and refreshes) a token itself with the
    # client-credentials grant.
    shopify_admin_token: str = ""
    shopify_client_id: str = ""
    shopify_client_secret: str = ""
    shopify_api_version: str = "2026-10"
    # Secret used to verify X-Shopify-Hmac-Sha256 on POST /api/webhooks/shopify/orders-create.
    # For a Dev Dashboard app this is the app's client secret; falls back to SHOPIFY_CLIENT_SECRET when empty.
    shopify_webhook_secret: str = ""
    # Shown under the QR code on stage, only when set (dev stores are password-protected by default).
    shopify_storefront_password: str = ""
    # Optional public short link to the product page shown on stage (e.g. a link you shortened yourself).
    # The QR code always encodes the full product URL.
    shopify_short_url: str = ""
    shopify_timeout: float = 20.0
    # Seconds between Admin API order polls while the pre-order window is open (works from localhost).
    shopify_poll_interval: float = 4.0
    # Publish the product to the Online Store sales channel after creating it.
    shopify_publish: bool = True
    # Count Bogus-Gateway / test-mode orders (order.test == true). A dev store only takes test orders.
    shopify_count_test_orders: bool = True
    # Real pre-order window length (hours of wall-clock time).
    shopify_demand_window_hours: float = 336.0
    # A real 300-unit run can't be crowd-funded on stage. When > 0, crossing this many real pre-order units
    # unlocks the PO instead; the UI always shows it as "stage threshold: N pre-orders (production plan: P units)".
    demand_stage_threshold: int = 0

    # --- derived -----------------------------------------------------------
    @property
    def llm_live(self) -> bool:
        """AMD vLLM (the direct brain path) is configured."""
        return bool(self.amd_vllm_endpoint.strip())

    @property
    def vision_live(self) -> bool:
        return bool(self.amd_vision_endpoint.strip())

    @property
    def diffusion_live(self) -> bool:
        return bool(self.amd_diffusion_endpoint.strip())

    @property
    def _evolus_base_ok(self) -> bool:
        # The REST API needs both X-ApiKey and X-Application-Id.
        return bool(self.evolus_api_base) and bool(self.evolus_api_key) and bool(self.evolus_workspace_id)

    @property
    def evolus_outreach_live(self) -> bool:
        return self._evolus_base_ok and bool(self.evolus_outreach_workflow_id)

    @property
    def negotiation_workflow_id(self) -> str:
        return (self.evolus_negotiation_workflow_id or self.evolus_outreach_workflow_id).strip()

    @property
    def evolus_negotiation_live(self) -> bool:
        return self._evolus_base_ok and bool(self.negotiation_workflow_id)

    @property
    def po_workflow_id(self) -> str:
        return (self.evolus_po_workflow_id or self.evolus_outreach_workflow_id).strip()

    @property
    def evolus_po_live(self) -> bool:
        return self._evolus_base_ok and bool(self.po_workflow_id)

    @property
    def evolus_shopify_live(self) -> bool:
        return self._evolus_base_ok and bool(self.evolus_shopify_workflow_id)

    @property
    def shopify_admin_ready(self) -> bool:
        """Direct Admin API access (create products, poll orders): real credentials are the opt-in."""
        return bool(self.shopify_store_domain.strip()) and bool(
            self.shopify_admin_token or (self.shopify_client_id and self.shopify_client_secret))

    @property
    def shopify_webhook_key(self) -> str:
        return self.shopify_webhook_secret or self.shopify_client_secret

    @property
    def shopify_base(self) -> str:
        d = self.shopify_store_domain.strip().rstrip("/")
        return d if d.startswith(("http://", "https://")) else f"https://{d}"

    @property
    def evolus_agent_live(self) -> bool:
        return self._evolus_base_ok and bool(self.evolus_agent_model.strip())

    @property
    def evolus_library_live(self) -> bool:
        return self._evolus_base_ok and bool(self.evolus_library_id.strip())

    @property
    def evolus_extractor_live(self) -> bool:
        return (self._evolus_base_ok and bool(self.evolus_extractor_id.strip())
                and bool(self.evolus_extractor_agent_id.strip()))

    @property
    def brain_live(self) -> bool:
        """Some real model can write tech packs / RFQs: the Evolus agent or direct vLLM."""
        return self.evolus_agent_live or self.llm_live

    @property
    def chat_base(self) -> str:
        return (self.evolus_chat_base or self.evolus_api_base).rstrip("/")

    @property
    def data_dir(self) -> Path:
        if not self.atelier_data_dir.strip():
            return BACKEND_DIR / "var"
        p = Path(self.atelier_data_dir).expanduser()
        return p if p.is_absolute() else BACKEND_DIR / p

    @property
    def cors_origin_list(self) -> list[str]:
        return [o.strip() for o in self.cors_origins.split(",") if o.strip()]

    def public_url(self, path: str) -> str:
        return f"{self.public_base_url.rstrip('/')}/{path.lstrip('/')}"


def host_of(url: str) -> str:
    try:
        return urlparse(url).netloc or url
    except Exception:  # pragma: no cover
        return url


@lru_cache
def get_settings() -> Settings:
    return Settings()
